#!/usr/bin/env python3
"""Requirements traceability: every requirement names the checks that verify it.

    python3 tools/trace.py            # rewrite docs/REQUIREMENTS.md from docs/requirements.json
    python3 tools/trace.py --check    # CI: fail if a named check no longer exists, a requirement
                                      # has no check, or docs/REQUIREMENTS.md is out of date

Standard library only. A check is named by the file it lives in and its exact
text. If someone renames or deletes a test, this fails until the requirement
is pointed at whatever verifies it now.
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
requirements = json.load(open(os.path.join(ROOT, "docs", "requirements.json")))
RUN = {
    "native/tests/test_cli.py": "npm test",
    "native/tests/test_planner.py": "npm test",
    "ml/evaluate.py": "npm run eval:model",
    "ml/outcome.py": "npm run eval:outcome",
    "ml/autonomy_eval.py": "npm run eval:autonomy",
    "ml/opponent_eval.py": "npm run eval:opponent",
    "ml/tracking_eval.py": "npm run eval:tracking",
    "sil/run_sil.py": "npm run sil",
    "ros2/check_bridge.py": "python3 ros2/check_bridge.py (CI job ros2)",
    "web/test_sessions.py": "npm run test:web",
}

problems = []
sources = {}
seen_ids = set()
for r in requirements:
    if r["id"] in seen_ids:
        problems.append(f"{r['id']}: used twice")
    seen_ids.add(r["id"])
    if not r["tests"]:
        problems.append(f"{r['id']}: no check verifies it")
    for path, name in r["tests"]:
        if path not in sources:
            full = os.path.join(ROOT, path)
            sources[path] = open(full).read() if os.path.exists(full) else None
        if sources[path] is None:
            problems.append(f"{r['id']}: {path} does not exist")
        elif f'"{name}"' not in sources[path]:
            problems.append(f"{r['id']}: no check named \"{name}\" in {path}")
        if path not in RUN:
            problems.append(f"{r['id']}: {path} is not run by any CI command listed in tools/trace.py")

# How much of each test file is traced back to a requirement.
traced = {}
for r in requirements:
    for path, name in r["tests"]:
        traced.setdefault(path, set()).add(name)
coverage = []
for path in ("native/tests/test_cli.py", "native/tests/test_planner.py"):
    names = set(re.findall(r'(?:check|rejected)\(\s*"((?:[^"\\]|\\.)*)"', sources.get(path) or ""))
    coverage.append((path, len(traced.get(path, set()) & names), len(names)))

out = ["# Requirements and the checks that verify them", "",
       "Generated by `python3 tools/trace.py` from `docs/requirements.json`. Do not edit by hand.", "",
       "Each requirement names the automated checks that verify it. CI runs `tools/trace.py --check`, which fails if a "
       "named check no longer exists or a requirement is left without one, so this table cannot quietly go stale.", ""]
area = None
for r in requirements:
    if r["area"] != area:
        area = r["area"]
        out += [f"## {area}", "", "| ID | Requirement | Verified by | Run with |", "| --- | --- | --- | --- |"]
    checks = "<br>".join(f"{name} (`{path}`)" for path, name in r["tests"])
    runs = ", ".join(sorted({f"`{RUN.get(path, '?')}`" for path, _ in r["tests"]}))
    out.append(f"| {r['id']} | {r['text']} | {checks} | {runs} |")
    if requirements.index(r) == len(requirements) - 1 or requirements[requirements.index(r) + 1]["area"] != area:
        out.append("")
out += ["## Coverage", "",
        f"{len(requirements)} requirements, {sum(len(r['tests']) for r in requirements)} links to checks.", ""]
for path, linked, total in coverage:
    out.append(f"- `{path}`: {linked} of {total} checks are linked to a requirement. The rest are input validation and "
               "regression checks that no requirement above depends on." if total else f"- `{path}`: not found")
out.append("")
report = "\n".join(out)

target = os.path.join(ROOT, "docs", "REQUIREMENTS.md")
if "--check" in sys.argv:
    if not os.path.exists(target) or open(target).read() != report:
        problems.append("docs/REQUIREMENTS.md is out of date: run python3 tools/trace.py")
else:
    with open(target, "w") as f:
        f.write(report)
for line in problems:
    print("FAIL  " + line)
if problems:
    sys.exit(1)
print(f"all {len(requirements)} requirements trace to existing checks")

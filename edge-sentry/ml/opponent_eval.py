#!/usr/bin/env python3
"""Both sides flown by the computer: how much harder is red's coordinated doctrine?

    python3 ml/opponent_eval.py                 # print the table, rewrite ml/OPPONENT.md
    python3 ml/opponent_eval.py --check         # also exit non-zero if a floor is missed
    python3 ml/opponent_eval.py --rollouts 20 --check --no-write   # the quick version CI runs

Standard library only. Each battle is a random layout: blue has headquarters,
three sensors or relays and a stealth fighter; red has a jammer and four to six
attackers on the far side of the map. Nobody has orders at the start. Red is
flown by `edge-sim opponent --side red` under one of two doctrines; blue by the
autonomy planner, or by nobody.
"""
import argparse
import os
import random
import sys

import simlab

p = argparse.ArgumentParser()
p.add_argument("--rollouts", type=int, default=80, help="random battles (seeds from 800000)")
p.add_argument("--check", action="store_true", help="fail if results fall below the floors")
p.add_argument("--no-write", action="store_true", help="do not rewrite ml/OPPONENT.md")
args = p.parse_args()

TICKS = 22
AIRCRAFT = {"jet", "stealth", "bomber", "drone", "missile"}


battle = simlab.battle_scenario  # the generator lives in simlab so the training code draws from the same one


def play(sim, units, doctrine, defend, variant="full"):
    state = sim.load(units)
    blue = [u["id"] for u in units if u["team"] == "blue"]
    values, hits, first = [], 0, None
    for _ in range(TICKS):
        sim.run("opponent", "--side", "red", "--doctrine", doctrine)
        if defend:
            sim.run("autopilot", "--variant", variant)
        world = sim.run("tick")["world"]
        values.append(sum((u["hp"] / 100.0) * u["integrity"] for u in world["units"] if u["id"] in blue and u["alive"]) / len(blue))
        for e in world["events"]:
            if e["tick"] == world["tick"] and e["kind"] == "engage" and e["detail"].split(" hit ")[-1] in blue:
                hits += 1
                first = first or world["tick"]
    final = world["units"]
    return {"value": sum(values) / len(values), "hits": hits,
            "blue_lost": sum(1 for u in final if u["team"] == "blue" and not u["alive"]),
            "red_down": sum(1 for u in final if u["team"] == "red" and not u["alive"] and u["type"] in AIRCRAFT and u["type"] != "missile"),
            "fighter": sum(1 for u in final if u["id"] == "B-F1" and u["alive"])}


CASES = [
    ("basic", False, "Original script", "nobody", "full"),
    ("basic", True, "Original script", "the planner", "full"),
    ("coordinated", False, "Coordinated doctrine", "nobody", "full"),
    ("coordinated", True, "Coordinated doctrine", "the planner before either lesson", "untaught"),
    ("coordinated", True, "Coordinated doctrine", "the planner with self-defense only", "gohome"),
    ("coordinated", True, "Coordinated doctrine", "the planner with pressing on only", "nodefense"),
    ("coordinated", True, "Coordinated doctrine", "the planner (both lessons)", "full"),
    ("coordinated", True, "Coordinated doctrine", "the planner, a close approach also counts as hostile", "closein"),
]
sim = simlab.Sim()
totals = [{"value": 0.0, "hits": 0, "blue_lost": 0, "red_down": 0, "fighter": 0} for _ in CASES]
for i in range(args.rollouts):
    units = battle(800000 + i)
    for k, (doctrine, defend, _, _, variant) in enumerate(CASES):
        r = play(sim, units, doctrine, defend, variant)
        for key in totals[k]:
            totals[k][key] += r[key]
avg = [{key: v / args.rollouts for key, v in t.items()} for t in totals]

out = ["# Red opponent results", "", "Generated by `python3 ml/opponent_eval.py`. Do not edit by hand.", ""]
out.append(f"Both sides flown by the computer over {args.rollouts} random battles of {TICKS} ticks: blue has headquarters, three "
           "sensors or relays and a stealth fighter; red has a jammer and four to six attackers. Mission value is blue's, "
           "so lower means red did better.")
out.append("")
out.append("| Red flown by | Blue flown by | Blue mission value | Hits on blue | Blue units lost | Red aircraft shot down | Blue's fighter survives |")
out.append("| --- | --- | --- | --- | --- | --- | --- |")
for (_, _, red, blue, _), a in zip(CASES, avg):
    out.append(f"| {red} | {blue} | {a['value']:.3f} | {a['hits']:.2f} | {a['blue_lost']:.2f} | {a['red_down']:.2f} | {a['fighter']:.0%} |")
out.append("")
out.append("The original script launched everything at once at the nearest target. The coordinated doctrine times the strike "
           "to arrive together, brings jets, drones and the stealth fighter in at level 1, sends the jammer to headquarters "
           "first, sends the stealth fighter after blue's fighter, and spreads the other attackers across different assets. "
           "It is built to beat a defense: against a blue that does nothing, holding to arrive together costs ticks and "
           "the two do about the same.")
out.append("")
out.append("The planner at first lost its fighter in almost half of these battles. Replaying them showed a damaged fighter "
           "turning for home with a hunter as fast as it is on its tail, and hold-fire stopping it from shooting back at a "
           "hunter the threat model scored low. Two lessons came out of that.")
out.append("")
out.append("Self-defense: a contact that has hit one of blue's aircraft may be shot at whatever its threat label, a damaged "
           "fighter fights the contact hunting it instead of running, and point defense may cover the hunter.")
out.append("")
out.append("Pressing on: nothing is repaired at headquarters, so a damaged fighter that goes home just leaves the battle "
           "while jets and drones keep hitting sensors. It now stays out of new fights with armed aircraft that have done "
           "nothing yet, but keeps attacking aircraft that cannot shoot back (bombers, drones) and aircraft already seen "
           "hitting a blue unit, which includes its own hunter.")
out.append("")
out.append("The two overlap: each alone stops the fighter turning its back on its hunter, so each alone gets most of the "
           "gain, and together they add a little more. The last row also treats a fighter closing to two cells at blue's "
           "level as hostile before it fires; `ml/AUTONOMY.md` shows what that costs in aircraft shot down that never "
           "attacked.")
out.append("")
report = "\n".join(out)
print(report)
if not args.no_write:
    with open(os.path.join(simlab.HERE, "OPPONENT.md"), "w") as f:
        f.write(report)

if args.check:
    before, defense, press, both = avg[3], avg[4], avg[5], avg[6]
    floors = [
        ("the coordinated doctrine hurt the planner more than the original script before it was taught", before["value"] < avg[1]["value"]),
        ("the planner still beats no defense against the coordinated doctrine", both["value"] > avg[2]["value"]),
        ("self-defense alone raises mission value against the coordinated doctrine", defense["value"] > before["value"]),
        ("self-defense keeps the fighter alive more often", defense["fighter"] > before["fighter"]),
        ("pressing on alone raises mission value against the coordinated doctrine", press["value"] > before["value"]),
        ("a damaged fighter that stays in the battle shoots down more of red's aircraft", both["red_down"] > defense["red_down"]),
        ("both lessons together do at least as well as either alone",
         both["value"] >= max(defense["value"], press["value"]) - 0.01 and both["fighter"] >= before["fighter"]),
    ]
    for name, ok in floors:
        print(("PASS  " if ok else "FAIL  ") + name)
    sys.exit(0 if all(ok for _, ok in floors) else 1)

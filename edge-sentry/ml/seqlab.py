"""Shared helpers for the sequence (GRU) threat model.

Standard library only, so evaluation runs without PyTorch. Training
(ml/train_seq.py) is the only step that needs it.

The model reads one contact's per-tick inputs in order and carries a hidden
state from tick to tick. It sees only the first SEQ_INPUTS model inputs, the
ones that describe the current tick (altitude and climb or descent included). The hand-built history inputs the default
model uses (ticks stopped, range closed and altitude lost over 3 ticks, lagged closing
and heading) are left out on purpose: the question is whether a recurrent model
can learn that history for itself.
"""
import json
import math
import os

import simlab

SEQ_INPUTS = simlab.SEQUENCE_INPUTS  # kSequenceInputs in native/src/aiml_scorer.hpp, reported by `edge-sim inputs`
INPUT_NAMES = simlab.MODEL_INPUTS[:SEQ_INPUTS]
MODEL_PATH = os.path.join(simlab.HERE, "sequence.json")
HEADER_PATH = os.path.join(simlab.ROOT, "native", "src", "sequence_weights.hpp")


def sequences(rows):
    """Group dataset rows into one sequence per contact per rollout, in tick order."""
    groups = {}
    for r in rows:
        groups.setdefault((r["seed"], r["id"]), []).append(r)
    out = []
    for key in sorted(groups):
        seq = sorted(groups[key], key=lambda r: r["tick"])
        out.append({
            "seed": key[0], "id": key[1], "rows": seq,
            "x": [r["observed"][:SEQ_INPUTS] for r in seq],
            "y": [r["harm"] for r in seq],
        })
    return out


def _sigmoid(v):
    return 1.0 / (1.0 + math.exp(-v))


def step(model, x, h):
    """One GRU step, same gate order (reset, update, new) and equations as torch.nn.GRU."""
    H = model["hidden"]
    gi = [b + sum(w * v for w, v in zip(ws, x)) for ws, b in zip(model["weight_ih"], model["bias_ih"])]
    gh = [b + sum(w * v for w, v in zip(ws, h)) for ws, b in zip(model["weight_hh"], model["bias_hh"])]
    out = []
    for j in range(H):
        r = _sigmoid(gi[j] + gh[j])
        z = _sigmoid(gi[H + j] + gh[H + j])
        n = math.tanh(gi[2 * H + j] + r * gh[2 * H + j])
        out.append((1.0 - z) * n + z * h[j])
    return out


def scores(model, xs):
    """Reference forward pass over one contact's ticks. Returns a score per tick."""
    h = [0.0] * model["hidden"]
    out = []
    for x in xs:
        h = step(model, x, h)
        out.append(_sigmoid(model["out_bias"] + sum(w * v for w, v in zip(model["out_weights"], h))))
    return out


def load():
    """The trained model, or None before the first training run."""
    if not os.path.exists(MODEL_PATH):
        return None
    with open(MODEL_PATH) as f:
        return json.load(f)


def _row(values):
    return "{" + ", ".join(repr(float(v)) for v in values) + "}"


def write(model, note):
    """Write ml/sequence.json and the C++ header compiled into edge-sim."""
    H = model["hidden"]
    assert len(model["weight_ih"]) == 3 * H and all(len(w) == SEQ_INPUTS for w in model["weight_ih"])
    assert len(model["weight_hh"]) == 3 * H and all(len(w) == H for w in model["weight_hh"])
    with open(MODEL_PATH, "w") as f:
        json.dump(model, f, indent=1)
        f.write("\n")
    lines = [
        "#pragma once",
        "// GENERATED by ml/train_seq.py. Do not edit by hand; retrain instead.",
        f"// GRU with {H} hidden units read one tick at a time, then a sigmoid output:",
        f"// P(contact harms a blue asset within {simlab.HORIZON} ticks).",
        f"// {note}",
        "// Inputs, in order: " + ", ".join(INPUT_NAMES),
        "// Weight rows follow torch.nn.GRU: reset gate, update gate, new gate.",
        "",
        "namespace edge_seq {",
        f"constexpr double kWatchAt = {model['watch_at']!r};",
        f"constexpr double kHostileAt = {model['hostile_at']!r};",
        f"constexpr int kNumInputs = {SEQ_INPUTS};",
        f"constexpr int kHidden = {H};",
        "constexpr double kWeightIh[3 * kHidden][kNumInputs] = {",
    ]
    lines += ["    " + _row(w) + "," for w in model["weight_ih"]]
    lines += ["};", "constexpr double kWeightHh[3 * kHidden][kHidden] = {"]
    lines += ["    " + _row(w) + "," for w in model["weight_hh"]]
    lines += [
        "};",
        f"constexpr double kBiasIh[3 * kHidden] = {_row(model['bias_ih'])};",
        f"constexpr double kBiasHh[3 * kHidden] = {_row(model['bias_hh'])};",
        f"constexpr double kOutWeights[kHidden] = {_row(model['out_weights'])};",
        f"constexpr double kOutBias = {float(model['out_bias'])!r};",
        "}  // namespace edge_seq",
        "",
    ]
    with open(HEADER_PATH, "w") as f:
        f.write("\n".join(lines))
